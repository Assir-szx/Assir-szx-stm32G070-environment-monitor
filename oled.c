static void OLED_WriteCmd(uint8_t cmd)
{
    HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR, 0x00, I2C_MEMADD_SIZE_8BIT, &cmd, 1, 0x100);
}

static void OLED_WriteData(uint8_t data)
{
    HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR, 0x40, I2C_MEMADD_SIZE_8BIT, &data, 1, 0x100);
}

void OLED_Init(void)
{
    HAL_Delay(100);
    printf("OLED Init start\r\n");

    // 完整的 SSD1306 初始化命令序列（包含开启电荷泵）
    uint8_t init_cmds[] = {
        0xAE, 0xD5, 0x80, 0xA8, 0x3F, 0xD3, 0x00, 0x40,
        0x8D, 0x14, 0x20, 0x00, 0xA1, 0xC8, 0xDA, 0x12,
        0x81, 0xFF, 0xD9, 0xF1, 0xDB, 0x30, 0xA4, 0xA6, 0xAF
    };

    for (int i = 0; i < sizeof(init_cmds); i++) {
        HAL_StatusTypeDef res = HAL_I2C_Mem_Write(&hi2c1, OLED_ADDR, 0x00, I2C_MEMADD_SIZE_8BIT, &init_cmds[i], 1, 100);
        if (res != HAL_OK) {
            printf("Init cmd %d failed: %d\r\n", i, res);
        }
        HAL_Delay(1);
    }

    printf("OLED Init commands sent\r\n");
    OLED_Clear();
    OLED_Update();
    printf("OLED Init done\r\n");
}

void OLED_Clear(void)
{
    for (int page = 0; page < 8; page++) {
        for (int col = 0; col < 128; col++) {
            OLED_Buffer[page][col] = 0x00;
        }
    }
}

void OLED_Update(void)
{
    for (int page = 0; page < 8; page++) {
        OLED_WriteCmd(0xB0 + page);
        OLED_WriteCmd(0x00);
        OLED_WriteCmd(0x10);
        for (int col = 0; col < 128; col++) {
            OLED_WriteData(OLED_Buffer[page][col]);
        }
    }
}

void OLED_ShowChar(uint8_t x, uint8_t y, char ch)
{
    if (x > 120 || y > 6) return;
    if (ch < 32 || ch > 127) ch = 32;

    for (int i = 0; i < 8; i++) {
        OLED_Buffer[y][x + i] = Font8x16[ch - 32][i];
        OLED_Buffer[y + 1][x + i] = Font8x16[ch - 32][i + 8];
    }
}

void OLED_ShowString(uint8_t x, uint8_t y, char *str)
{
    while (*str) {
        OLED_ShowChar(x, y, *str);
        x += 8;
        if (x > 120) {
            x = 0;
            y += 2;
        }
        str++;
    }
    OLED_Update();
}

void OLED_ShowNum(uint8_t x, uint8_t y, uint32_t num, uint8_t len)
{
    char buf[11];
    sprintf(buf, "%0*d", len, num);
    OLED_ShowString(x, y, buf);
}
