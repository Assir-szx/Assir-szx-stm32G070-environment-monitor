void OLED_ShowChinese(uint8_t x, uint8_t y, uint8_t index)
{
    if (x > 112 || y > 6) return;

    // 列行式读取：先写上半部分，再写下半部分
    for (int i = 0; i < 16; i++) {
        // 上半部分 (前16字节)
        OLED_Buffer[y][x + i] = ChineseFont[index][i];
        // 下半部分 (后16字节)
        OLED_Buffer[y + 1][x + i] = ChineseFont[index][i + 16];
    }
}
